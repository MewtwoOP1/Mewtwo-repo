const assert = require('node:assert/strict');
const provider = require('../providers/uniquestream.js');
const oldFetch = global.fetch;
const calls = [];
const seriesHtml = `<main><h1>Sample Series</h1><meta name="description" content="A test series"><meta property="og:image" content="https://media.uniquestream.net/posters/sample.jpg"><section><a href="/watch/abc123/Episode-1">Episode 1</a><a href="/watch/def456/Episode-2">Episode 2</a></section></main>`;
const searchHtml = `<main><article><a href="/series/series1/Sample-Series"><h2>Sample Series</h2><img src="https://media.uniquestream.net/posters/sample.jpg"></a></article></main>`;
global.fetch = async (url, opts) => {
  const u = String(url); calls.push({url:u,opts:opts||{}});
  if (u.includes('/search?q=Sample%20Series')) return {status:200,body:searchHtml};
  if (u.includes('/search/?q=')) return {status:200,body:searchHtml};
  if (u === 'https://anime.uniquestream.net/series/series1/Sample-Series/') return {status:200,body:seriesHtml};
  if (u === 'https://anime.uniquestream.net/series/series1/Sample-Series') return {status:200,body:seriesHtml};
  if (u === 'https://anime.uniquestream.net/watch/abc123/Episode-1') return {status:200,body:`<video><source src="https://media.uniquestream.net/video/episode1.m3u8"></video>`};
  if (u === 'https://anime.uniquestream.net/watch/def456/Episode-2') return {status:200,body:'<main>Playback not available</main>'};
  if (u.includes('/search?q=missing')) return {status:200,body:'<main>No titles</main>'};
  if (u.includes('/search?q=malformed')) return {status:200,body:'<html><div'};
  if (u.includes('/videos/popular/')) return {status:200,body:searchHtml};
  if (u.includes('/watch/err/')) throw new Error('network down');
  return {status:404,body:'not found'};
};
async function main() {
  assert.equal(provider.version,'0.1.0');
  assert.equal(provider.getInfo().name,'Uniquestream');
  assert.deepEqual(await provider.search(''),[]);
  assert.equal((await provider.search('Sample Series')).length,1);
  assert.deepEqual(await provider.search('missing'),[]);
  assert.deepEqual(await provider.search('malformed'),[]);
  assert.deepEqual(await provider.search('network error'),[]);
  const found=(await provider.search('Sample Series'))[0];
  const detail=await provider.getDetail(found.url);
  assert.equal(detail.title,'Sample Series');
  assert.equal(detail.description,'A test series');
  assert.equal(detail.episodes.length,2);
  assert.equal(detail.episodes[1].number,2);
  const streams=await provider.getVideoSources(detail.episodes[0].url);
  assert.equal(streams.length,1);
  assert.equal(streams[0].url,'https://media.uniquestream.net/video/episode1.m3u8');
  await assert.rejects(provider.getVideoSources('invalid'),/invalid episode URL/);
  await assert.rejects(provider.getVideoSources(detail.episodes[1].url),/did not expose/);
  await assert.rejects(provider.getVideoSources('uniquestream://episode/'+encodeURIComponent('https://evil.example/watch/aa')),/invalid watch page/);
  const backup='https://media.uniquestream.net/video/fallback.mp4';
  global.fetch=async (url)=>({status:200,body:'<script type="application/ld+json">'+JSON.stringify({contentUrl:backup})+'</script>'});
  const fallback=await provider.getVideoSources(detail.episodes[0].url);
  assert.equal(fallback[0].url,backup);
  await assert.rejects(provider.getVideoSources('uniquestream://episode/%E0%A4%A'),/malformed episode/);
  global.fetch=async()=>{throw new Error('offline');};
  assert.deepEqual(await provider.search('failure'),[]);
  await assert.rejects(provider.getVideoSources(detail.episodes[0].url),/offline/);
  console.log('Uniquestream mocked tests passed ('+calls.length+' mocked requests).');
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{global.fetch=oldFetch;});
