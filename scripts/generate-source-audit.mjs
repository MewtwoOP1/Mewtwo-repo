#!/usr/bin/env node
/**
 * Generates docs/cinestream-source-audit.md.
 *
 * The movie and anime inventories are kept in docs/source-audit.json so the
 * generator only has to render them; the provider counts are cross-checked
 * against providers/cinestream.js so the document can never claim a count
 * the code does not have.
 *
 * Usage: node scripts/generate-source-audit.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const notesPath = path.join(rootDir, "docs", "source-audit.json");
const outPath = path.join(rootDir, "docs", "cinestream-source-audit.md");
const providerFile = path.join(rootDir, "providers", "cinestream.js");
const check = process.argv.includes("--check");

const notes = JSON.parse(fs.readFileSync(notesPath, "utf8"));
const providerSrc = fs.readFileSync(providerFile, "utf8");

function registryKeys() {
  const m = providerSrc.match(/var PROVIDERS = \[([\s\S]*?)\n\];/);
  if (!m) return [];
  const out = [];
  const re = /\['(p_[a-z0-9_]+)',\s*'([^']+)'\]/g;
  let x;
  while ((x = re.exec(m[1])) !== null) out.push({ key: x[1], name: x[2] });
  return out;
}
function animeOnlyKeys() {
  const m = providerSrc.match(/var ANIME_ONLY = \{([\s\S]*?)\n\};/);
  if (!m) return [];
  return (m[1].match(/p_[a-z0-9_]+/g) || []);
}

const registry = registryKeys();
const animeOnly = animeOnlyKeys();
const animeKeys = new Set(animeOnly);

function table(rows) {
  if (!rows.length) return "_None._\n";
  const head = "| Provider | Domain / API | Backend identity | Search | Details | Episodes | Servers | Extractors | Configuration | Formats | Playback | Ranking |\n";
  const sep = "|---|---|---|---|---|---|---|---|---|---|---|---|\n";
  return head + sep + rows.map((r) =>
    "| **" + r.name + "** | " + r.domain + " | " + r.backend + " | " + r.search + " | " + r.details +
    " | " + r.episodes + " | " + r.servers + " | " + r.extractors + " | " + r.config + " | " + r.formats +
    " | " + r.playback + " | " + r.ranking + " |"
  ).join("\n") + "\n";
}

function render() {
  const movieRows = notes.movie || [];
  const animeRows = notes.anime || [];
  const total = registry.length;
  const movieCount = registry.filter((r) => !animeKeys.has(r.key)).length;
  const animeCount = animeKeys.size;

  let out = "";
  out += "# CineStream source audit\n\n";
  out += "Generated by `node scripts/generate-source-audit.mjs` — do not edit by hand.\n\n";
  out += "This document tracks every provider CineStream registers, split into **movies** and **anime**, with the\n";
  out += "state of its search, details, episode discovery, server collection, extraction and Zangetsu playback.\n\n";

  out += "## Totals\n\n";
  out += "| Metric | Count |\n|---|---|\n";
  out += "| Registered providers (HTTP + subtitle) | **" + total + "** |\n";
  out += "| Movie-capable providers | **" + movieCount + "** |\n";
  out += "| Anime-only providers | **" + animeCount + "** |\n";
  out += "| Shared extractors | " + (notes.extractors ? notes.extractors.length : 0) + " |\n\n";

  out += "Status vocabulary: **PASS** (the step was carried out and succeeded), **FAIL** (attempted and failed),\n";
  out += "**BLOCKED** (a real external dependency prevents it), **UNVERIFIED** (not enough evidence),\n";
  out += "**N/A** (does not apply).\n\n";

  out += "## Movie providers (" + movieCount + ")\n\n";
  out += table(movieRows);
  out += "\n";
  out += "## Anime providers (" + animeCount + ")\n\n";
  out += table(animeRows);
  out += "\n";
  out += "## Shared extractors\n\n";
  if (notes.extractors) {
    out += "| Extractor | Hosts |\n|---|---|\n";
    for (const e of notes.extractors) out += "| `" + e.name + "` | " + e.hosts + " |\n";
    out += "\n";
  }
  out += "## Ranking\n\n";
  out += notes.ranking || "_No ranking description._\n\n";
  out += "## Verification\n\n";
  out += notes.verification || "_No verification note._\n";
  return out;
}

const rendered = render();
if (check) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  if (current !== rendered) {
    console.error("[FAIL] docs/cinestream-source-audit.md is stale — run node scripts/generate-source-audit.mjs");
    process.exit(1);
  }
  console.log("[PASS] docs/cinestream-source-audit.md is up to date");
} else {
  fs.writeFileSync(outPath, rendered);
  console.log("[PASS] Wrote docs/cinestream-source-audit.md (" + rendered.split("\n").length + " lines)");
}
